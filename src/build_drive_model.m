function build_drive_model()
%BUILD_DRIVE_MODEL  v0.3: ramped reference + acceleration feedforward on the v0.2 cascade.
%   Speed controller:  i_ref = sat( PI(w_ref - w) + J_nom/K * dw_ref/dt , +-Imax )
%   Creates models/dcmotor_drive.slx (overwrites it). Parameters: drive_params.m

mdl = 'dcmotor_drive';
drive_params;
new_model(mdl);

%% Blocks
add_block('simulink/Sources/Step', [mdl '/Speed Setpoint'], 'Time', 'scn.t_ref', ...
    'Before', '0', 'After', 'scn.w_ref', 'Position', [20 95 60 135]);
add_block('simulink/Discontinuities/Rate Limiter', [mdl '/Ramp'], ...
    'RisingSlewLimit', 'ctrl.w_slew', 'FallingSlewLimit', '-ctrl.w_slew', ...
    'Position', [90 100 130 130]);
add_block('simulink/Sources/Step', [mdl '/Load Torque'], 'Time', 'scn.t_load', ...
    'Before', '0', 'After', 'scn.TL', 'Position', [560 195 600 235]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/Speed Controller'],   'Position', [180 90 300 170]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/Current Controller'], 'Position', [380 90 500 170]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/DC Motor'],           'Position', [640 90 760 210]);
add_block('simulink/Signal Routing/Mux', [mdl '/Mux_w'], 'Inputs', '2', 'Position', [850 20 855 70]);
add_block('simulink/Signal Routing/Mux', [mdl '/Mux_i'], 'Inputs', '2', 'Position', [850 90 855 140]);
add_block('simulink/Sinks/Scope', [mdl '/Scope'], 'NumInputPorts', '3', 'Position', [910 30 950 150]);

add_speed_controller_ff([mdl '/Speed Controller']);
add_pi_loop([mdl '/Current Controller'], 'i_ref', 'i', 'V', 'Current PI', ...
    'ctrl.Kp_i', 'ctrl.Ki_i', 'ctrl.Vmax', 'ctrl.Ts_i');
add_dcmotor_plant([mdl '/DC Motor']);

%% Wiring
wire(mdl, 'Speed Setpoint/1',     'Ramp/1', ...
          'Ramp/1',               'Speed Controller/1', ...
          'Speed Controller/1',   'Current Controller/1', ...
          'Current Controller/1', 'DC Motor/1', ...
          'Load Torque/1',        'DC Motor/2', ...
          'DC Motor/1',           'Speed Controller/2', ...
          'DC Motor/2',           'Current Controller/2', ...
          'Ramp/1',               'Mux_w/1', ...
          'DC Motor/1',           'Mux_w/2', ...
          'Speed Controller/1',   'Mux_i/1', ...
          'DC Motor/2',           'Mux_i/2', ...
          'Mux_w/1', 'Scope/1',   'Mux_i/1', 'Scope/2', ...
          'Current Controller/1', 'Scope/3');
add_logging(mdl, {'w_ref_log', 'Ramp/1';              'w_log', 'DC Motor/1'; ...
                  'i_ref_log', 'Speed Controller/1';  'i_log', 'DC Motor/2'; ...
                  'V_log', 'Current Controller/1';    'TL_log', 'Load Torque/1'}, 910, 270);

name_signal(mdl, 'Speed Setpoint', 1, 'w_set');     name_signal(mdl, 'Ramp', 1, 'w_ref');
name_signal(mdl, 'Speed Controller', 1, 'i_ref');   name_signal(mdl, 'Current Controller', 1, 'V');
name_signal(mdl, 'DC Motor', 1, 'w');               name_signal(mdl, 'DC Motor', 2, 'i');
name_signal(mdl, 'Load Torque', 1, 'TL');

%% Configuration
set_param(mdl, 'InitFcn', 'drive_params; apply_scenario;', ...
    'Solver', 'ode45', 'StopTime', num2str(scn.t_stop), ...
    'RelTol', '1e-6', 'MaxStep', '1e-4', 'ReturnWorkspaceOutputs', 'on', ...
    'Description', 'v0.3 DC motor drive: reference ramp + acceleration feedforward + cascade PI.');
add_note(mdl, 'v0.3: ramped reference + acceleration feedforward, speed PI (1 kHz) to current PI (10 kHz, 5 A)', [20 30]);
save_model(mdl);
end

function add_speed_controller_ff(sys)
%ADD_SPEED_CONTROLLER_FF  Speed PI plus acceleration feedforward, then the current limit.
%   i_ff = J_nom/K * (w_ref[k] - w_ref[k-1]) / Ts_w
clear_subsystem(sys);
add_block('simulink/Sources/In1', [sys '/w_ref'], 'Position', [20 43 50 57]);
add_block('simulink/Sources/In1', [sys '/w'],     'Position', [20 123 50 137]);
add_block('simulink/Discrete/Zero-Order Hold', [sys '/Sample'], ...
    'SampleTime', 'ctrl.Ts_w', 'Position', [80 35 110 65]);
add_block('simulink/Math Operations/Sum', [sys '/Error'], 'Inputs', '+-', ...
    'IconShape', 'round', 'Position', [150 120 170 140]);
add_pi_block(sys, 'Speed PI', 'ctrl.Kp_w', 'ctrl.Ki_w', 'ctrl.Imax', 'ctrl.Ts_w', [200 110 280 150]);

add_block('simulink/Discrete/Unit Delay', [sys '/Prev ref'], ...
    'SampleTime', 'ctrl.Ts_w', 'InitialCondition', '0', 'Position', [150 20 180 50]);
add_block('simulink/Math Operations/Sum', [sys '/dRef'], 'Inputs', '+-', ...
    'IconShape', 'round', 'Position', [220 25 240 45]);
add_block('simulink/Math Operations/Gain', [sys '/Accel FF'], ...
    'Gain', 'ctrl.J_nom/(motor.K*ctrl.Ts_w)', 'Position', [270 20 330 50]);
add_block('simulink/Math Operations/Sum', [sys '/Add FF'], 'Inputs', '++', ...
    'IconShape', 'round', 'Position', [360 80 380 100]);
add_block('simulink/Discontinuities/Saturation', [sys '/Current Limit'], ...
    'UpperLimit', 'ctrl.Imax', 'LowerLimit', '-ctrl.Imax', 'Position', [410 75 450 105]);
add_block('simulink/Sinks/Out1', [sys '/i_ref'], 'Position', [490 83 520 97]);

wire(sys, 'w_ref/1', 'Sample/1',     'Sample/1', 'Error/1',     'w/1', 'Error/2', ...
          'Error/1', 'Speed PI/1', ...
          'Sample/1', 'Prev ref/1',  'Sample/1', 'dRef/1',      'Prev ref/1', 'dRef/2', ...
          'dRef/1', 'Accel FF/1',    'Accel FF/1', 'Add FF/1',  'Speed PI/1', 'Add FF/2', ...
          'Add FF/1', 'Current Limit/1', 'Current Limit/1', 'i_ref/1');
Simulink.BlockDiagram.arrangeSystem(sys);
end
