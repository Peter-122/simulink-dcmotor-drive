function build_cascade_model()
%BUILD_CASCADE_MODEL  v0.2: speed PI -> current PI -> motor, with a 5 A current limit.
%   Both controllers are discrete (speed 1 kHz, current 10 kHz) with
%   clamping anti-windup. Creates models/dcmotor_cascade.slx (overwrites it).
%   Parameters: cascade_params.m

mdl = 'dcmotor_cascade';
cascade_params;
new_model(mdl);

%% Blocks
add_block('simulink/Sources/Step', [mdl '/Speed Ref'], 'Time', 'scn.t_ref', ...
    'Before', '0', 'After', 'scn.w_ref', 'Position', [30 95 70 135]);
add_block('simulink/Sources/Step', [mdl '/Load Torque'], 'Time', 'scn.t_load', ...
    'Before', '0', 'After', 'scn.TL', 'Position', [500 185 540 225]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/Speed Controller'],   'Position', [130 90 250 170]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/Current Controller'], 'Position', [320 90 440 170]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/DC Motor'],           'Position', [590 90 710 210]);
add_block('simulink/Signal Routing/Mux', [mdl '/Mux_w'], 'Inputs', '2', 'Position', [800 20 805 70]);
add_block('simulink/Signal Routing/Mux', [mdl '/Mux_i'], 'Inputs', '2', 'Position', [800 90 805 140]);
add_block('simulink/Sinks/Scope', [mdl '/Scope'], 'NumInputPorts', '3', 'Position', [860 30 900 150]);

add_pi_loop([mdl '/Speed Controller'], 'w_ref', 'w', 'i_ref', 'Speed PI', ...
    'ctrl.Kp_w', 'ctrl.Ki_w', 'ctrl.Imax', 'ctrl.Ts_w');
add_pi_loop([mdl '/Current Controller'], 'i_ref', 'i', 'V', 'Current PI', ...
    'ctrl.Kp_i', 'ctrl.Ki_i', 'ctrl.Vmax', 'ctrl.Ts_i');
add_dcmotor_plant([mdl '/DC Motor']);

%% Wiring
wire(mdl, 'Speed Ref/1',          'Speed Controller/1', ...
          'Speed Controller/1',   'Current Controller/1', ...
          'Current Controller/1', 'DC Motor/1', ...
          'Load Torque/1',        'DC Motor/2', ...
          'DC Motor/1',           'Speed Controller/2', ...
          'DC Motor/2',           'Current Controller/2', ...
          'Speed Ref/1',          'Mux_w/1', ...
          'DC Motor/1',           'Mux_w/2', ...
          'Speed Controller/1',   'Mux_i/1', ...
          'DC Motor/2',           'Mux_i/2', ...
          'Mux_w/1', 'Scope/1',   'Mux_i/1', 'Scope/2', ...
          'Current Controller/1', 'Scope/3');
add_logging(mdl, {'w_ref_log', 'Speed Ref/1';         'w_log', 'DC Motor/1'; ...
                  'i_ref_log', 'Speed Controller/1';  'i_log', 'DC Motor/2'; ...
                  'V_log', 'Current Controller/1';    'TL_log', 'Load Torque/1'}, 860, 270);

name_signal(mdl, 'Speed Ref', 1, 'w_ref');          name_signal(mdl, 'Speed Controller', 1, 'i_ref');
name_signal(mdl, 'Current Controller', 1, 'V');     name_signal(mdl, 'DC Motor', 1, 'w');
name_signal(mdl, 'DC Motor', 2, 'i');               name_signal(mdl, 'Load Torque', 1, 'TL');

%% Configuration
set_param(mdl, 'InitFcn', 'cascade_params; apply_scenario;', ...
    'Solver', 'ode45', 'StopTime', num2str(scn.t_stop), ...
    'RelTol', '1e-6', 'MaxStep', '1e-4', 'ReturnWorkspaceOutputs', 'on', ...
    'Description', 'v0.2 cascade DC motor drive: speed PI (1 kHz) -> current PI (10 kHz, 5 A limit).');
add_note(mdl, 'v0.2: speed PI (1 kHz) to current PI (10 kHz, 5 A limit) to motor', [30 30]);
save_model(mdl);
end
